using Content.Client._Utopia.Helpers;
using Content.Shared._Utopia.ShiftSchedule;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.CustomControls;
using Robust.Client.UserInterface.XAML;

namespace Content.Client._Utopia.ShiftSchedule;

[GenerateTypedNameReferences]
public sealed partial class ShiftScheduleConsoleMenu : DefaultWindow
{
    private int? _currentId;
    private bool _canEdit;
    private bool _isEnabled = true;

    private ShiftScheduleEntryState[] _entries = [];

    public event Action<int?, string, int, string>? OnSave;
    public event Action<int>? OnRemove;
    public event Action<bool>? OnToggle;
    public event Action<int>? OnAnnounce;
    public event Action<string>? OnImportCode;

    public ShiftScheduleConsoleMenu()
    {
        RobustXamlLoader.Load(this);

        TitleInput.IsValid = value => value.Trim().Length is > 0 and <= 80;
        DescriptionInput.IsValid = value => value.Length <= 500;

        HoursInput.OnTextChanged += _ => UtopiaHelper.ValidateLineEditNumbers(HoursInput, 2);
        MinutesInput.OnTextChanged += _ => UtopiaHelper.ValidateLineEditNumbers(MinutesInput, 2);
        SecondsInput.OnTextChanged += _ => UtopiaHelper.ValidateLineEditNumbers(SecondsInput, 2);

        SaveButton.OnButtonUp += OnSavePressed;
        CancelButton.OnButtonUp += _ => ClearForm();
        ToggleButton.OnButtonUp += _ => OnToggle?.Invoke(!_isEnabled);
        ExportCodeButton.OnButtonUp += _ => ExportCode();
        ImportCodeButton.OnButtonUp += _ => ImportCode();
    }

    public void UpdateState(ShiftScheduleConsoleInterfaceState state)
    {
        _canEdit = state.CanEdit;
        _isEnabled = state.Enabled;
        _entries = state.Entries;

        TitleInput.Editable = _canEdit;
        HoursInput.Editable = _canEdit;
        MinutesInput.Editable = _canEdit;
        SecondsInput.Editable = _canEdit;
        DescriptionInput.Editable = _canEdit;
        SaveButton.Disabled = !_canEdit;
        CancelButton.Disabled = !_canEdit;
        ToggleButton.Disabled = !_canEdit;
        ScheduleCodeInput.Editable = _canEdit;
        ExportCodeButton.Disabled = !_canEdit;
        ImportCodeButton.Disabled = !_canEdit;

        ToggleButton.Text = Loc.GetString(_isEnabled
            ? "shift-schedule-turn-off"
            : "shift-schedule-turn-on"
        );

        StatusLabel.Text = state.Status ?? "";

        if (state.Clear)
        {
            ClearForm();
        }

        EntriesContainer.Children.Clear();
        for (var index = 0; index < state.Entries.Length; index++)
        {
            var entry = state.Entries[index];
            var row = new ShiftScheduleEntryControl();
            row.SetEntry(entry, _canEdit, _isEnabled);
            row.OnEdit += _ => EditEntry(entry);
            row.OnAnnounce += id => OnAnnounce?.Invoke(id);
            row.OnRemove += id => OnRemove?.Invoke(id);
            EntriesContainer.AddChild(row);
        }
    }

    private void OnSavePressed(BaseButton.ButtonEventArgs args)
    {
        if (!_canEdit)
            return;

        if (TitleInput.Text.Trim().Length is 0 or > 80
        || DescriptionInput.Text.Length > 500
        || !TryParseTime(HoursInput.Text, MinutesInput.Text, SecondsInput.Text, out var timeSeconds))
        {
            StatusLabel.Text = Loc.GetString("shift-schedule-invalid-entry");
            return;
        }

        OnSave?.Invoke(_currentId, TitleInput.Text.Trim(), timeSeconds, DescriptionInput.Text.Trim());
    }

    private void EditEntry(ShiftScheduleEntryState entry)
    {
        _currentId = entry.Id;

        TitleInput.Text = entry.Title;
        HoursInput.Text = $"{entry.Time / 3600:00}";
        MinutesInput.Text = $"{entry.Time / 60 % 60:00}";
        SecondsInput.Text = $"{entry.Time % 60:00}";
        DescriptionInput.Text = entry.Description;

        SaveButton.Text = Loc.GetString("shift-schedule-save");
    }

    private void ClearForm()
    {
        _currentId = null;

        TitleInput.Text = "";
        HoursInput.Text = "";
        MinutesInput.Text = "";
        SecondsInput.Text = "";
        DescriptionInput.Text = "";

        SaveButton.Text = Loc.GetString("shift-schedule-add");
    }

    private void ExportCode()
    {
        ScheduleCodeInput.Text = ShiftScheduleCode.Encode(_entries);
        StatusLabel.Text = Loc.GetString("shift-schedule-code-exported");
    }

    private void ImportCode()
    {
        var code = ScheduleCodeInput.Text.Trim();
        if (string.IsNullOrWhiteSpace(code) || code.Length > ShiftScheduleCode.MaxCodeLength)
        {
            StatusLabel.Text = Loc.GetString("shift-schedule-code-invalid");
            return;
        }

        OnImportCode?.Invoke(code);
    }

    private static bool TryParseTime(string hoursText, string minutesText, string secondsText, out int timeTime)
    {
        timeTime = 0;

        if (hoursText.Length != 2 || minutesText.Length != 2 || secondsText.Length != 2
        || !int.TryParse(hoursText, out var hours)
        || !int.TryParse(minutesText, out var minutes)
        || !int.TryParse(secondsText, out var seconds)
        || hours > 99 || minutes > 59 || seconds > 59)
            return false;

        timeTime = hours * 60 + minutes * 60 + seconds * 60;
        return true;
    }
}
