using Content.Shared._Utopia.ShiftSchedule;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;

namespace Content.Client._Utopia.ShiftSchedule;

[GenerateTypedNameReferences]
public sealed partial class ShiftScheduleEntryControl : BoxContainer
{
    private int _entryId;

    public event Action<int>? OnEdit;
    public event Action<int>? OnAnnounce;
    public event Action<int>? OnRemove;

    public ShiftScheduleEntryControl()
    {
        RobustXamlLoader.Load(this);

        EditButton.OnButtonUp += _ => OnEdit?.Invoke(_entryId);
        AnnounceButton.OnButtonUp += _ => OnAnnounce?.Invoke(_entryId);
        RemoveButton.OnButtonUp += _ => OnRemove?.Invoke(_entryId);
    }

    public void SetEntry(ShiftScheduleEntryState entry, bool canEdit, bool scheduleEnabled)
    {
        _entryId = entry.Id;

        var hours = entry.Time / 3600;
        var minutes = entry.Time / 60 % 60;
        var seconds = entry.Time % 60;

        TimeLabel.Text = $"{hours:00}:{minutes:00}:{seconds:00}";
        TitleLabel.Text = entry.Title;
        DescriptionLabel.Text = entry.Description;
        DescriptionLabel.Visible = !string.IsNullOrWhiteSpace(entry.Description);
        EditButton.Disabled = !canEdit;
        AnnounceButton.Disabled = !canEdit || !scheduleEnabled;
        RemoveButton.Disabled = !canEdit;
    }
}
